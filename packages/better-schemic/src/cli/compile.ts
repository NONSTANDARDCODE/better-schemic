/**
 * `sc compile` — AOT validation for authored `s.*` fields, powered by zod-compiler.
 *
 * `s.*` fields wrap a Zod schema; zod-compiler's auto-discovery cannot see a Zod schema hidden
 * inside an exported `TableDef`. So we generate a synthetic module that re-exports each field's
 * underlying Zod schema, let zod-compiler compile THAT into a static `.compiled.ts`, and write a
 * bootstrap module which imports the compiled file for its side effects and re-exports the
 * original definitions. zod-compiler mutates the original schema objects in place, so the
 * SurrealQL metadata, `.shape`, `instanceof` and the ORM stay intact — validation gains a fast path.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import nodePath from "node:path"
import { fileURLToPath } from "node:url"

import { configureJiti, loadDefs, normalizeAliases, type ResolvedConfig } from "../core"
import { applyDirectives, type GeneratedOpts } from "../core/cli-kit/generated"
import { rewriteZodSpecifiers } from "../core/cli-kit/zod-specifier"
import type { AnyField } from "../surreal"

import { resolveOne, type ResolveOpts } from "./resolve"

export type CompileTarget = {
  /** Export name of the authored table in its source module. */
  readonly exportName: string
  readonly fields: readonly string[]
  /** Absolute path of that source module. */
  readonly sourceFile: string
  readonly table: string
}

const spec = (from: string, to: string): string => {
  const rel = nodePath.relative(nodePath.dirname(from), to).replaceAll("\\", "/")
  return rel.startsWith("../") ? rel : `./${rel}`
}

const ident = (name: string): string => name.replaceAll(/[^A-Za-z0-9_$]/gu, "_")

/** Pure renderer for the synthetic module of raw Zod schemas (unit-testable). */
export function renderSyntheticSource(targets: readonly CompileTarget[], outFile: string): string {
  const lines = [
    "// GENERATED by `sc compile` — DO NOT EDIT. Regenerate after a schema change.",
    'import { fieldSchemaOf } from "better-schemic/aot";',
    "",
  ]
  targets.forEach((target, ti) => {
    lines.push(
      `import { ${target.exportName} as __bs_def_${ti} } from "${spec(outFile, target.sourceFile)}";`,
    )
    target.fields.forEach((field) => {
      lines.push(
        `export const __bs_${ti}_${ident(field)} = fieldSchemaOf(__bs_def_${ti}.fields[${JSON.stringify(field)}]);`,
      )
    })
  })
  return `${lines.join("\n")}\n`
}

/** Pure renderer for the bootstrap module the app imports instead of its schema module. */
export function renderBootstrapSource(
  targets: readonly CompileTarget[],
  outFile: string,
  compiledFile: string,
): string {
  const lines = [
    "// GENERATED by `sc compile` — DO NOT EDIT.",
    "// Importing this module installs the AOT-compiled validators on the original schemas.",
    `import "${spec(outFile, compiledFile)}";`,
    "",
    ...targets.map((t) => `export { ${t.exportName} } from "${spec(outFile, t.sourceFile)}";`),
  ]
  return `${lines.join("\n")}\n`
}

export type CompileOpts = {
  /** Generated sources directory (default `<root>/.better-schemic/aot`). */
  readonly dir?: string
  /** Bootstrap module (default from the config's `generators.aot`, else `<root>/.better-schemic/schema.aot.ts`). */
  readonly out?: string
  /** Emit sources without invoking zod-compiler (useful in tests/CI inspection). */
  readonly sourcesOnly?: boolean
} & ResolveOpts

export type CompileResult = {
  readonly bootstrap: string
  readonly compiled: string
  readonly schemaCount: number
  readonly synthetic: string
  readonly targets: readonly CompileTarget[]
}

/** CLI action: discover every authored field schema, compile it, and write the bootstrap module. */
export async function compileAot(opts: CompileOpts = {}): Promise<CompileResult> {
  return compileAotWith(await resolveOne(opts), opts)
}

/**
 * The generator body, driven by an ALREADY resolved config — `sc generate` resolves once and runs
 * both generators against the same project (no second config load, no symlinks).
 */
export async function compileAotWith(
  config: ResolvedConfig,
  opts: CompileOpts = {},
): Promise<CompileResult> {
  configureJiti({
    alias: config.project?.resolve?.alias,
    root: config.root,
    tsconfigPaths: config.project?.resolve?.tsconfigPaths,
  })
  const loaded = await loadDefs(config.schemaPath)
  const aotConfig = config.project?.generators?.aot
  const configured = typeof aotConfig === "object" ? aotConfig : undefined
  // Keep generated files OUT of the schema directory: `loadDefs` scans every .ts under it and
  // would treat a bootstrap module re-exporting the tables as a duplicate definition.
  const dir = nodePath.resolve(config.root, opts.dir ?? configured?.dir ?? ".better-schemic/aot")
  const out = nodePath.resolve(
    config.root,
    opts.out ?? configured?.out ?? ".better-schemic/schema.aot.ts",
  )
  const synthetic = nodePath.join(dir, "schemas.ts")
  const compiled = nodePath.join(dir, "schemas.compiled.ts")
  const generated = config.project?.generated
  const directives: GeneratedOpts = {
    eslintDisable: generated?.eslintDisable,
    marker: generated?.marker,
    tsNocheck: generated?.tsNocheck,
  }

  const targets: CompileTarget[] = loaded.tables.flatMap((def) => {
    const sourceFile = loaded.fileOf.get(def)
    if (!sourceFile) return []

    const entities = loaded.localEntities.get(sourceFile)?.entities ?? []
    const entity = entities.find(
      (e) => e.kind === "table" && e.name === (def as { name: string }).name,
    )
    if (!entity) return []

    const fields = Object.keys((def as unknown as { fields: Record<string, AnyField> }).fields)
    return fields.length > 0
      ? [
          {
            exportName: entity.exportName,
            fields,
            sourceFile,
            table: (def as { name: string }).name,
          },
        ]
      : []
  })

  mkdirSync(dir, { recursive: true })
  writeFileSync(synthetic, renderSyntheticSource(targets, synthetic))
  applyDirectives(synthetic, directives, ["// GENERATED by `sc compile` — DO NOT EDIT."])

  if (!opts.sourcesOnly) {
    const bin = nodePath.join(
      nodePath.dirname(fileURLToPath(import.meta.resolve("zod-compiler"))),
      "cli",
      "index.js",
    )
    // zod-compiler loads the synthetic module with its OWN jiti instance; pass the project aliases
    // through the environment so a schema importing `@/env` compiles without a node_modules symlink.
    const aliases = normalizeAliases({
      alias: config.project?.resolve?.alias,
      root: config.root,
    })
    const proc = Bun.spawnSync([process.execPath, bin, "generate", synthetic, "-o", compiled], {
      cwd: config.root,
      env: {
        ...process.env,
        ...(Object.keys(aliases).length > 0 ? { JITI_ALIAS: JSON.stringify(aliases) } : {}),
        ...(config.project?.resolve?.tsconfigPaths
          ? {
              JITI_TSCONFIG_PATHS:
                typeof config.project.resolve.tsconfigPaths === "string"
                  ? config.project.resolve.tsconfigPaths
                  : "true",
            }
          : {}),
      },
      stderr: "pipe",
      stdout: "pipe",
    })
    if (proc.exitCode !== 0) {
      const err = new TextDecoder().decode(proc.stderr)
      const hint =
        Object.keys(config.project?.resolve?.alias ?? {}).length > 0
          ? "\n\nAliases in `resolve.alias` must also appear in the app's tsconfig `paths`: zod-compiler resolves imports with get-tsconfig, not jiti."
          : ""
      throw new Error(`sc compile: zod-compiler failed:\n${err}${hint}`)
    }
    // zod-compiler hardcodes `from "zod"` and `from "zod/v4/core"`. Point both at specifiers this
    // package owns, so an app never gains a SECOND Zod copy (which would break `instanceof`).
    writeFileSync(
      compiled,
      rewriteZodSpecifiers(
        readFileSync(compiled, "utf8"),
        generated?.zodSpecifier ?? "better-schemic/zod",
      ),
    )
    applyDirectives(compiled, directives, ["// GENERATED by zod-compiler — DO NOT EDIT."])
  }

  writeFileSync(out, renderBootstrapSource(targets, out, compiled))
  applyDirectives(out, directives, ["// GENERATED by `sc compile` — DO NOT EDIT."])
  return {
    bootstrap: out,
    compiled,
    schemaCount: targets.reduce((n, t) => n + t.fields.length, 0),
    synthetic,
    targets,
  }
}
