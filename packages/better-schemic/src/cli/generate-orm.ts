/**
 * `sc generate:orm` — generate a STATIC-getter façade over the typed ORM client.
 *
 * Why: Bun's AOT can only give a fixed layout to getters written in the source. The runtime client
 * installs one delegate getter per schema key via `Object.defineProperty` in a loop — convenient,
 * but a slow path in the generated binary. This command reads the authored schema (the single
 * source of truth) and emits the equivalent getters as plain TypeScript, with an `OrmSurface`
 * `satisfies` check so a new model cannot silently go missing from the façade.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { makeJiti, type ResolvedConfig } from "../core";
import { SCHEMA_DEF } from "../surreal/orm/types/schema";
import { type ResolveOpts, resolveOne } from "./resolve";

export interface RenderOrmSurfaceOpts {
  readonly models: readonly string[];
  /** Module specifier for the schema type import (relative to the generated file). */
  readonly schemaImport: string;
  /** Exported schema artifact name in that module. */
  readonly schemaExport: string;
  /** Module specifier for the client resolver import. */
  readonly providerImport: string;
  /** Expression that returns the client, e.g. `getOrmClient`. */
  readonly clientExpr: string;
  /** Name of the generated const. */
  readonly surfaceName?: string;
}

const FIXED_MEMBERS = [
  "$query",
  "$raw",
  "$unsafe",
  "$sdk",
  "repository",
  "tables",
  "transaction",
] as const;

/** Pure renderer — no filesystem, so the generated shape is unit-testable. */
export function renderOrmSurface(opts: RenderOrmSurfaceOpts): string {
  const name = opts.surfaceName ?? "orm";
  const members = [...FIXED_MEMBERS, ...opts.models];
  const lines = [
    "// GENERATED by `sc generate:orm` — do not edit. Regenerate after changing the schema.",
    'import type { OrmSurface } from "better-schemic/orm";',
    `import type { ${opts.schemaExport} } from "${opts.schemaImport}";`,
    `import { ${opts.clientExpr} } from "${opts.providerImport}";`,
    "",
    `export const ${name} = {`,
    ...members.flatMap((key) => [
      `  /** Static getter — AOT-friendly view of the runtime delegate. */`,
      `  get ${key}() {`,
      `    return ${opts.clientExpr}().${key};`,
      `  },`,
    ]),
    `} satisfies OrmSurface<typeof ${opts.schemaExport}>;`,
    "",
  ];
  return lines.join("\n");
}

export interface GenerateOrmOpts extends ResolveOpts {
  /** Output .ts file (default `<root>/db/orm.generated.ts`). */
  readonly out?: string;
  /** Module exporting the schema artifact (default: the configured schema path when a file). */
  readonly schema?: string;
  /** Export name of the schema artifact. */
  readonly schemaExport?: string;
  /** Module exporting the client resolver. */
  readonly providerFrom?: string;
  /** Expression returning the client. */
  readonly client?: string;
  /** Name of the generated const. */
  readonly surfaceName?: string;
}

/** CLI action: load the schema artifact, discover its model keys, write the generated façade. */
export async function generateOrm(opts: GenerateOrmOpts): Promise<string> {
  const config: ResolvedConfig = await resolveOne(opts);
  const out = opts.out ?? join(config.root, "db/orm.generated.ts");
  const schemaFile = opts.schema ?? config.schemaPath;
  const jiti = makeJiti();
  const mod = (await jiti.import(schemaFile)) as Record<string, unknown>;
  let entries: Record<string, unknown> | undefined;
  for (const value of Object.values(mod)) {
    if (
      value &&
      typeof value === "object" &&
      (value as Record<symbol, unknown>)[SCHEMA_DEF] === true &&
      "entries" in value
    ) {
      entries = (value as { entries: Record<string, unknown> }).entries;
      break;
    }
  }
  if (!entries)
    throw new Error(
      `generate:orm: no schema artifact (SCHEMA_DEF) exported from ${schemaFile} — pass --schema <file>.`,
    );
  const found = entries;
  const models = Object.keys(found).filter((key) => {
    const value = found[key];
    return (
      typeof value === "string" ||
      (value !== null &&
        typeof value === "object" &&
        "fields" in value &&
        "name" in value)
    );
  });
  const relPath = (from: string, to: string) => {
    const spec = relative(dirname(from), to).replaceAll("\\", "/");
    return spec.startsWith("../") ? spec : `./${spec}`;
  };
  const source = renderOrmSurface({
    models,
    schemaImport: relPath(out, schemaFile).replace(/\.[cm]?[jt]s$/, ""),
    schemaExport: opts.schemaExport ?? "schema",
    providerImport: opts.providerFrom ?? "./orm",
    clientExpr: opts.client ?? "getOrmClient",
    surfaceName: opts.surfaceName,
  });
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, source);
  return out;
}
