/**
 * `sc generate:orm` — generate a STATIC-getter façade over the typed ORM client.
 *
 * Why: Bun's AOT gives a fixed layout to getters written in the source. The runtime client installs
 * one delegate getter per schema key via `Object.defineProperty` in a loop — convenient, but a slow
 * path in the generated binary. This command reads the authored schema (the single source of truth)
 * and emits those getters as plain TypeScript, with an `OrmSurface` `satisfies` check so a new model
 * cannot go missing from the façade without a type error.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"

import { configureJiti, makeJiti, type ResolvedConfig } from "../core"
import { applyDirectives, type GeneratedOpts } from "../core/cli-kit/generated"
import { SCHEMA_DEF } from "../surreal/orm/types/schema"
import { resolveOne, type ResolveOpts } from "./resolve"

export interface RenderOrmSurfaceOpts {
  /** Expression that returns the client, e.g. `getOrmClient`. */
  readonly clientExpr: string
  readonly models: readonly string[]
  /** Module specifier for the client resolver import. */
  readonly providerImport: string
  /** Exported schema artifact name in that module. */
  readonly schemaExport: string
  /** Module specifier for the schema type import (relative to the generated file). */
  readonly schemaImport: string
  /** Name of the generated const. */
  readonly surfaceName?: string
}

const FIXED_MEMBERS = [
  "$query",
  "$raw",
  "$unsafe",
  "$sdk",
  "repository",
  "tables",
  "transaction",
] as const

/** Pure renderer — no filesystem, so the generated shape is unit-testable. */
export function renderOrmSurface(opts: RenderOrmSurfaceOpts): string {
  const name = opts.surfaceName ?? "orm"
  const members = [...FIXED_MEMBERS, ...opts.models]
  const lines = [
    "// GENERATED by `sc generate:orm` — do not edit. Regenerate after changing the schema.",
    'import type { OrmSurface } from "better-schemic/orm";',
    `import type { ${opts.schemaExport} } from "${opts.schemaImport}";`,
    `import { ${opts.clientExpr} } from "${opts.providerImport}";`,
    "",
    `export const ${name} = {`,
    ...members.flatMap((key) => [
      `  /** Static getter — AOT-friendly view of the runtime delegate. */`,
      `  get ${key}() {`,
      `    return ${opts.clientExpr}().${key};`,
      `  },`,
    ]),
    `} satisfies OrmSurface<typeof ${opts.schemaExport}>;`,
    "",
  ]
  return lines.join("\n")
}

export type GenerateOrmOpts = {
  /** Expression returning the client. */
  readonly client?: string
  /** Output .ts file (default from the config, else `<root>/db/orm.generated.ts`). */
  readonly out?: string
  /** Module exporting the client resolver. */
  readonly providerFrom?: string
  /** Module exporting the schema artifact (default: the configured schema path when a file). */
  readonly schema?: string
  /** Export name of the schema artifact. */
  readonly schemaExport?: string
  /** Name of the generated const. */
  readonly surfaceName?: string
} & ResolveOpts

const relPath = (from: string, to: string): string => {
  const spec = relative(dirname(from), to).replaceAll("\\", "/")
  return spec.startsWith("../") ? spec : `./${spec}`
}

/** CLI action: load the schema artifact, discover its model keys, write the generated façade. */
export async function generateOrm(opts: GenerateOrmOpts): Promise<string> {
  return generateOrmWith(await resolveOne(opts), opts)
}

/** The generator body, driven by an already resolved config (`sc generate` reuses one resolution). */
export async function generateOrmWith(
  config: ResolvedConfig,
  opts: GenerateOrmOpts,
): Promise<string> {
  configureJiti({
    alias: config.project?.resolve?.alias,
    root: config.root,
    tsconfigPaths: config.project?.resolve?.tsconfigPaths,
  })
  const ormConfig = config.project?.generators?.orm
  const configured = typeof ormConfig === "object" ? ormConfig : undefined
  const out = resolve(config.root, opts.out ?? configured?.out ?? "db/orm.generated.ts")
  const schemaFile = resolve(config.root, opts.schema ?? configured?.schema ?? config.schemaPath)
  if (!existsSync(schemaFile)) {
    throw new Error(`generate:orm: schema module not found: ${schemaFile}`)
  }

  const jiti = makeJiti()
  const mod = await jiti.import<Record<string, unknown>>(schemaFile)
  const schemaDef = Object.values(mod).find(
    (value) =>
      value !== null &&
      typeof value === "object" &&
      (value as Record<symbol, unknown>)[SCHEMA_DEF] === true &&
      "entries" in value,
  )
  const entries = schemaDef
    ? (schemaDef as { entries: Record<string, unknown> }).entries
    : undefined
  if (!entries) {
    throw new Error(
      `generate:orm: no schema artifact (SCHEMA_DEF) exported from ${schemaFile} — pass \`generators.orm.schema\`.`,
    )
  }
  const found = entries
  const models = Object.keys(found).filter((key) => {
    const value = found[key]
    return (
      typeof value === "string" ||
      (value !== null && typeof value === "object" && "fields" in value && "name" in value)
    )
  })
  /** A config path may be root-relative (`./src/db/provider.ts`) or an already-relative import. */
  const importFrom = (spec: string): string => {
    const absolute = resolve(config.root, spec)
    return existsSync(absolute) ? relPath(out, absolute).replace(/\.[cm]?[jt]s$/u, "") : spec
  }
  const source = renderOrmSurface({
    clientExpr: opts.client ?? configured?.client ?? "getOrmClient",
    models,
    providerImport: importFrom(opts.providerFrom ?? configured?.provider ?? "./orm"),
    schemaExport: opts.schemaExport ?? configured?.schemaExport ?? "schema",
    schemaImport: relPath(out, schemaFile).replace(/\.[cm]?[jt]s$/u, ""),
    surfaceName: opts.surfaceName ?? configured?.surface,
  })
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, source)
  const generated = config.project?.generated
  const directives: GeneratedOpts = {
    eslintDisable: generated?.eslintDisable,
    marker: generated?.marker,
    tsNocheck: generated?.tsNocheck,
  }
  applyDirectives(out, directives, ["// GENERATED by `sc generate:orm` — do not edit."])
  return out
}

/** Re-export for callers that need a filesystem-free default output path. */
export const defaultOrmOutput = (root: string): string => join(root, "db", "orm.generated.ts")
